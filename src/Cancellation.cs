using System;
using System.Collections.Generic;
using System.IO;

namespace ExcelMerger
{
    /// <summary>
    /// Кооперативная отмена длинных операций: сервисы проверяют предикат между единицами
    /// работы (страница/часть/файл) и бросают <see cref="OperationCanceledException"/>.
    /// Предикат обычно читает volatile-флаг, выставляемый кнопкой «Отмена» на UI-потоке;
    /// чтение bool из другого потока безопасно (без рвущихся чтений). null — без отмены.
    ///
    /// Вторая половина того же договора — инвариант «отмена не оставляет частичного
    /// результата» (<see cref="NoPartialOutput"/>): сервисы, пишущие ОДИН файл, сохраняют
    /// его в самом конце, а пишущие по файлу на единицу работы удаляют созданное.
    /// </summary>
    internal static class Cancellation
    {
        public static void ThrowIf(Func<bool> cancelled)
        {
            if (cancelled != null && cancelled())
                throw new OperationCanceledException();
        }

        /// <summary>
        /// Выполнить работу, создающую файлы ПО ОДНОМУ, под инвариантом «незавершённая работа не
        /// оставляет частичного результата»: созданное к моменту остановки удаляется, а причина
        /// остановки уходит наверх. Работа складывает путь в переданный список сразу после
        /// создания каждого файла — иначе удалять будет нечего. Возвращает этот список.
        ///
        /// Убирается ЛЮБАЯ остановка, не только отмена. Раньше сбой посреди работы оставлял в
        /// папке всё, что успело записаться, — а окно при этом говорило «не выполнено». Из папки
        /// с семью частями от сорока не видно, что она неполная: половина набора выглядит как
        /// набор, и следом её несут дальше как готовую. Причина остановки тут вообще не важна:
        /// разделения не произошло, значит и файлов быть не должно. Исключение одно — нехватка
        /// памяти: там уже не до уборки, и трогать что-либо опаснее, чем не трогать.
        ///
        /// Обёртка, а не catch по месту: блок повторялся дословно в трёх режимах разделения, а
        /// в четвёртом месте (сохранение страниц картинками) его просто забыли — отменённый
        /// экспорт оставлял в папке уже сохранённые картинки.
        /// </summary>
        public static List<string> NoPartialOutput(Action<List<string>> produce)
        {
            var created = new List<string>();
            try
            {
                produce(created);
            }
            catch (OutOfMemoryException)
            {
                throw; // не до уборки: любое лишнее действие здесь может не состояться
            }
            catch (Exception)
            {
                DeleteQuietly(created);
                throw;
            }
            return created;
        }

        /// <summary>
        /// Удалить файлы, созданные до остановки (best-effort — сбой удаления не важен).
        /// Открыт наружу: отменить можно и ПОСЛЕ того, как работа вернула список файлов, —
        /// сжатие идёт отдельной фазой и длится дольше самой нарезки.
        /// </summary>
        public static void DeleteQuietly(IEnumerable<string> paths)
        {
            foreach (string path in paths)
                try { if (File.Exists(path)) File.Delete(path); } catch { }
        }
    }
}
