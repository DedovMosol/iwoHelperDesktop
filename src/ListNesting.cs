using System;
using System.Collections.Generic;

namespace ExcelMerger
{
    /// <summary>
    /// Уровень вложенности пункта списка по его левому краю. Уровни держатся СТЕКОМ открытых
    /// отступов — тем же приёмом, каким по отступам разбирают блочный синтаксис: пункт правее
    /// вершины открывает уровень, пункт левее закрывает столько уровней, сколько нужно, чтобы
    /// вернуться к своему. Отсюда два свойства, которых не даёт нумерация кластеров:
    ///
    ///  • Уровень — ГЛУБИНА отступа, а не порядковый номер встреченного края. Пункт с отступом
    ///    между двумя известными уровнями возвращается на подходящий, а не объявляет себя
    ///    глубже всех (иначе иерархия в .docx выходила перевёрнутой).
    ///  • Возврат к прежнему отступу закрывает вложенные уровни сам, поэтому второй список
    ///    после первого не наследует его глубину — отдельный сброс не нужен.
    ///
    /// Порог <see cref="MinNestStepPt"/> отделяет настоящую вложенность от дрожания левого края:
    /// строки-продолжения и неровный край одного плоского списка отступают на единицы пунктов,
    /// а реальный вложенный уровень — на 18 pt и более (шаг списка по умолчанию у Word — 0,25").
    /// Без этого порога плоский список выходил в Word трёхуровневым.
    ///
    /// SRP: только уровни, ничего про запись в Word. Экземпляр — на один регион разметки.
    /// </summary>
    internal sealed class ListNesting
    {
        /// <summary>
        /// Наименьший отступ (pt), считающийся вложенностью. Меньше — тот же уровень с
        /// неровным краем. Шаг списка Word — 18 pt (0,25"), поэтому 12 pt принимает настоящую
        /// вложенность даже при сжатой вёрстке и гасит дрожание края.
        /// </summary>
        internal const double MinNestStepPt = 12.0;

        /// <summary>Максимум уровней: столько поддерживает нумерация Word.</summary>
        internal const int MaxLevel = 8; // 0..8 — девять уровней списка Word

        // Левые края открытых уровней, от корневого к самому глубокому. Индекс = уровень.
        private readonly List<double> _open = new List<double>();

        /// <summary>
        /// Уровень пункта с левым краем <paramref name="leftPt"/>: 0 — корневой, далее глубже.
        /// Вызывать по пунктам в порядке чтения — уровень зависит от уже открытых отступов.
        /// </summary>
        public int LevelFor(double leftPt)
        {
            // Первый пункт задаёт корневой уровень, каким бы ни был его отступ: список целиком
            // может стоять с отбивкой, и мерить её как вложенность не от чего.
            if (_open.Count == 0)
            {
                _open.Add(leftPt);
                return 0;
            }

            // Закрываем уровни, которые пункт оставил позади (его край левее их отступа).
            while (_open.Count > 1 && leftPt < _open[_open.Count - 1] - MinNestStepPt)
                _open.RemoveAt(_open.Count - 1);

            double top = _open[_open.Count - 1];

            // Заметно правее вершины — открыт новый уровень (до предела Word).
            if (leftPt > top + MinNestStepPt && _open.Count - 1 < MaxLevel)
            {
                _open.Add(leftPt);
                return _open.Count - 1;
            }

            // Иначе это вершина: тот же уровень. Левее корня (весь список сдвинулся) — тоже он,
            // корень при этом переезжает, чтобы дальнейшая вложенность мерилась от нового края.
            if (_open.Count == 1 && leftPt < top - MinNestStepPt)
                _open[0] = leftPt;
            return _open.Count - 1;
        }
    }
}
