namespace ExcelMerger
{
    /// <summary>
    /// Для какого вывода разбирается страница. Разбор один, но два вопроса он решает
    /// по-разному, и решить их одинаково нельзя.
    ///
    /// <b>Документ</b> — вывод ПОТОКОВЫЙ (Word): текст льётся строками, координат у абзаца
    /// нет. Значит строку надо беречь целиком (иначе фраза распадётся на куски), а линию
    /// приходится подменять прочерком из подчёркиваний — по-другому её в поток не поставить.
    ///
    /// <b>Слайд</b> — вывод с АБСОЛЮТНЫМИ координатами (PowerPoint): у каждой надписи своя
    /// рамка. Здесь всё наоборот: строку из независимых подписей надо резать по зазорам,
    /// иначе подписи слипаются и уезжают от того, что подписывают, а рисовать линии
    /// подчёркиваниями не нужно вовсе — их приносит подложка страницы.
    ///
    /// Режим влияет ТОЛЬКО на эти два решения; всё остальное в разборе общее.
    /// </summary>
    public enum PageLayoutMode
    {
        Document,
        Slide
    }
}
