namespace ExcelMerger
{
    /// <summary>
    /// Инструмент, которому можно передать файлы извне (дроп на карточку стартового
    /// экрана): открытый или только что созданный, он принимает пути и загружает их
    /// сам, как при обычном добавлении. Реализуют PDF-инструменты.
    /// </summary>
    internal interface IFileAcceptor
    {
        /// <summary>Принять файлы (уже отфильтрованные по расширению). Пустой/занятый — no-op.</summary>
        void AcceptFiles(string[] paths);
    }
}
