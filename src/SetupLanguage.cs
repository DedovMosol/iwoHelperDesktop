using System;
using System.IO;

namespace ExcelMerger
{
    /// <summary>
    /// Язык, выбранный флагом в установщике. Установщик кладёт рядом с настройками файл в одну
    /// ASCII-строку («ru» или «en»), приложение применяет его при первом запуске и убирает.
    ///
    /// Почему отдельный файл, а не строка в settings.txt: установщик пишет текст в СИСТЕМНОЙ
    /// кодировке, а приложение читает и пишет UTF-8. Правка общего файла из установщика
    /// испортила бы всё не-ASCII внутри — например кириллические пути последних папок. Поэтому
    /// settings.txt остаётся за приложением целиком, а установщику отдана одна ASCII-строка.
    ///
    /// Выбор установщика СТАРШЕ сохранённого языка: переустановка с другим флагом обязана
    /// открыть программу на новом языке — до 1.17.9 этого не происходило, потому что установщик
    /// пропускал запись, если settings.txt уже существовал.
    /// </summary>
    internal static class SetupLanguage
    {
        /// <summary>
        /// Выбор установщика: «ru», «en» или null, если файла нет либо в нём что-то иное.
        /// Файл здесь НЕ удаляется: служебные режимы запуска (самопроверка, пробы вшитых
        /// зависимостей) читают язык так же, как GUI, и не должны съедать выбор пользователя.
        /// Удаляет его <see cref="Consume"/> — уже на пути настоящего запуска.
        /// </summary>
        public static string Read()
        {
            try
            {
                string path = AppPaths.SetupLanguageFile;
                if (!File.Exists(path))
                    return null;
                foreach (string line in File.ReadAllLines(path))
                {
                    string code = line.Trim();
                    if (code == "ru" || code == "en")
                        return code;
                }
            }
            catch { } // недоступный или повреждённый файл — просто нет выбора установщика
            return null;
        }

        /// <summary>
        /// Снять маркер: язык уже применён и сохранён в настройках приложения, второй раз
        /// применять его нельзя — иначе он вечно перебивал бы выбор, сделанный в самой
        /// программе. Если файл удалить не удалось (занят), опустошаем его: пустой маркер
        /// <see cref="Read"/> не признаёт.
        /// </summary>
        public static void Consume()
        {
            string path = AppPaths.SetupLanguageFile;
            try
            {
                File.Delete(path);
                return;
            }
            catch { }
            try { File.WriteAllText(path, string.Empty); }
            catch { } // не вышло и это — на следующем запуске язык просто применится повторно
        }
    }
}
