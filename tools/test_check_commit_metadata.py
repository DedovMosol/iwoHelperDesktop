import shutil
import stat
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import check_commit_metadata as cm  # noqa: E402

OWNER = ("DedovMosol", "andreyid@outlook.com")
WEB = ("Andrey Dodonov", "73111581+DedovMosol@users.noreply.github.com")
GITHUB = ("GitHub", "noreply@github.com")
STRANGER = ("Someone", "someone@example.com")
TRAILER = "Co-Authored-By: Helper Bot <bot@example.com>"


def remove_tree(path):
    """Удалить временную папку целиком. git пишет объекты только для чтения, и на Windows
    rmtree без снятия атрибута их не удаляет; ignore_errors прятал это, и каждый прогон
    оставлял в %TEMP% по репозиторию на тест. Сбой здесь — ошибка теста, а не тихая утечка."""
    def retry(func, target, _):
        os.chmod(target, stat.S_IWRITE)
        func(target)
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=retry)
    else:
        shutil.rmtree(path, onerror=retry)


class PureRules(unittest.TestCase):
    def test_trailer_is_attribution_in_any_case_and_spacing(self):
        for line in ("Co-authored-by: X <x@y>", "co-authored-by:X", "  CO-AUTHORED-BY :  X"):
            self.assertEqual([line], cm.attribution_lines("Fix\n\n" + line + "\n"), line)

    def test_session_link_and_badged_signature_are_attribution(self):
        message = "Fix\n\nTool-Session: https://example.com/s/1\n\u2728 Generated with Tool\n"
        self.assertEqual(2, len(cm.attribution_lines(message)))

    def test_ordinary_text_is_not_attribution(self):
        message = ("Generated files updated\n\nRegenerated by the build; see "
                   "co-authored-by: docs.\nSession: https://example.com is a link\n")
        self.assertEqual([], cm.attribution_lines(message))

    def test_strip_keeps_clean_message_byte_for_byte(self):
        for message in ("Fix\n", "Fix", "Fix\n\nBody line\n\n", "Заголовок\r\n\r\nТекст\r\n"):
            self.assertIs(message, cm.strip_attribution(message))

    def test_strip_removes_trailers_and_the_blank_lines_they_leave(self):
        message = "Fix grid\n\nBody stays.\n\n" + TRAILER + "\nCo-authored-by: Other <o@x>\n"
        self.assertEqual("Fix grid\n\nBody stays.\n", cm.strip_attribution(message))

    def test_identity_matching_is_case_insensitive_and_exact(self):
        self.assertTrue(cm.is_author(" AndreyID@Outlook.com "))
        self.assertTrue(cm.is_author(WEB[1].upper()))
        self.assertFalse(cm.is_author("andreyid@outlook.com.evil"))
        self.assertFalse(cm.is_author(""))
        self.assertFalse(cm.is_author(GITHUB[1]), "GitHub автором быть не может")
        self.assertTrue(cm.is_committer(GITHUB[1]), "но коммитит правки из веб-интерфейса")


class TempRepo(unittest.TestCase):
    """Временный репозиторий без глобальных и системных настроек машины."""

    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix="iwo_meta_")
        self.addCleanup(remove_tree, self.dir)
        self.env = dict(os.environ)
        for key in list(self.env):
            if key.startswith("GIT_"):
                del self.env[key]
        self.env["GIT_CONFIG_GLOBAL"] = os.devnull
        self.env["GIT_CONFIG_NOSYSTEM"] = "1"
        self.git("init", "-q")
        self.counter = 0

    def git(self, *args, **kwargs):
        env = dict(self.env)
        env.update(kwargs.pop("env", {}))
        return subprocess.run(["git"] + list(args), cwd=self.dir, env=env,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, **kwargs)

    def commit(self, message, author=OWNER, committer=None, extra=()):
        committer = committer or author
        self.counter += 1
        with open(os.path.join(self.dir, "f.txt"), "w") as handle:
            handle.write(str(self.counter))
        self.git("add", "f.txt")
        env = {"GIT_AUTHOR_NAME": author[0], "GIT_AUTHOR_EMAIL": author[1],
               "GIT_COMMITTER_NAME": committer[0], "GIT_COMMITTER_EMAIL": committer[1]}
        return self.git("commit", "-q", "-m", message, *extra, env=env)

    def violations(self):
        return cm.history_violations(self.dir)


class History(TempRepo):
    def test_owner_history_with_web_edits_is_clean(self):
        self.commit("First")
        self.commit("Edit on the website", author=WEB, committer=GITHUB)
        self.assertEqual([], self.violations())

    def test_foreign_author_is_reported_with_commit_and_email(self):
        self.commit("First")
        self.commit("Theirs", author=STRANGER)
        problems = self.violations()
        self.assertEqual(2, len(problems), problems)  # автор и коммитер одного коммита
        self.assertTrue(all(STRANGER[1] in p for p in problems), problems)

    def test_foreign_committer_alone_is_reported(self):
        self.commit("Rebased by someone", committer=STRANGER)
        self.assertEqual(1, len(self.violations()))

    def test_trailer_anywhere_in_history_is_reported(self):
        self.commit("Clean")
        self.commit("With helper\n\n" + TRAILER)
        self.commit("Clean again")
        problems = self.violations()
        self.assertEqual(1, len(problems), problems)
        self.assertIn("Co-Authored-By", problems[0])

    def test_commit_reachable_only_from_a_tag_is_checked(self):
        self.commit("Main")
        self.git("checkout", "-q", "-b", "side")
        self.commit("Side\n\n" + TRAILER)
        self.git("tag", "v1")
        self.git("checkout", "-q", "-")
        self.git("branch", "-D", "side")
        self.assertEqual(1, len(self.violations()), "старая история под тегом — тоже история")

    def test_annotated_tag_by_foreign_tagger_is_reported(self):
        self.commit("Main")
        env = {"GIT_COMMITTER_NAME": STRANGER[0], "GIT_COMMITTER_EMAIL": STRANGER[1]}
        self.git("tag", "-a", "v2", "-m", "Release", env=env)
        self.git("tag", "light")  # лёгкий тег автора не имеет — нарушением не считается
        problems = self.violations()
        self.assertEqual(1, len(problems), problems)
        self.assertIn("v2", problems[0])

    def test_main_returns_one_on_violations_and_zero_when_clean(self):
        self.commit("Clean")
        self.assertEqual(0, cm.main(["--repo", self.dir]))
        self.commit("Bad\n\n" + TRAILER)
        self.assertEqual(1, cm.main(["--repo", self.dir]))

    def test_main_returns_two_when_not_a_repository(self):
        empty = tempfile.mkdtemp(prefix="iwo_norepo_")
        self.addCleanup(remove_tree, empty)
        self.assertEqual(2, cm.main(["--repo", empty]))


class HookFile(unittest.TestCase):
    def test_hook_has_unix_line_endings(self):
        # sh не исполняет скрипт с CRLF; .gitattributes держит хук в LF и на Windows.
        with open(os.path.join(HERE, "githooks", "commit-msg"), "rb") as handle:
            self.assertNotIn(b"\r", handle.read())


class Hook(TempRepo):
    """Хук из репозитория, подключённый так же, как в инструкции (core.hooksPath)."""

    def setUp(self):
        super(Hook, self).setUp()
        hooks = os.path.join(self.dir, "tools", "githooks")
        os.makedirs(hooks)
        shutil.copy(os.path.join(HERE, "githooks", "commit-msg"), hooks)
        shutil.copy(os.path.join(HERE, "check_commit_metadata.py"), os.path.join(self.dir, "tools"))
        self.git("config", "core.hooksPath", "tools/githooks")

    def message(self):
        return self.git("log", "-1", "--format=%B").stdout.decode("utf-8")

    def test_trailer_is_removed_and_commit_goes_through(self):
        result = self.commit("Fix grid\n\nBody.\n\n" + TRAILER)
        self.assertEqual(0, result.returncode, result.stderr)
        self.assertEqual("Fix grid\n\nBody.\n\n", self.message())

    def test_clean_message_is_left_exactly_as_written(self):
        self.commit("Заголовок\n\nТекст с пустой строкой\n\nи хвостом")
        self.assertEqual("Заголовок\n\nТекст с пустой строкой\n\nи хвостом\n\n", self.message())

    def test_foreign_author_is_rejected_and_nothing_is_committed(self):
        self.commit("First")
        result = self.commit("Theirs", author=STRANGER)
        self.assertNotEqual(0, result.returncode)
        self.assertIn(STRANGER[1], result.stderr.decode("utf-8"))
        self.assertEqual("1", self.git("rev-list", "--count", "HEAD").stdout.decode().strip())

    def test_author_override_flag_is_seen_by_the_hook(self):
        result = self.commit("Theirs", extra=("--author", "%s <%s>" % STRANGER))
        self.assertNotEqual(0, result.returncode, "--author обходил бы проверку")

    def test_amend_of_a_foreign_commit_is_rejected(self):
        self.commit("Theirs", author=STRANGER, extra=("--no-verify",))
        env = {"GIT_COMMITTER_NAME": OWNER[0], "GIT_COMMITTER_EMAIL": OWNER[1]}
        result = self.git("commit", "-q", "--amend", "-m", "Reword", env=env)
        self.assertNotEqual(0, result.returncode, "amend сохраняет чужого автора")


